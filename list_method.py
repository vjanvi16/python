
# List methods :-

# sort() :-

l1 = [3,12,4,7,16,8,22,11]
l1.sort()
print(l1)


# append() :-

l1.append(6)    # append means add new data in the end of list.
print(l1)


# reverse() :-

l1.reverse()
print(l1)


#  index() :-

print(l1.index(16))    # It will print index number of 16.


# count() :-

print(l1.count(16))    # It will count that how many times value 16 come in list.


# insert() :-

l1.insert(3,11)   # It will insert value 11 at index number 3
print(l1)

