# STRING SLICING :-

# LENGTH OF STRING :-

# We can find length of string using len() function.

fruit = "mango"
print(len(fruit))


# SLICING WITH STRING :-

name = "harry,parry"
print(len(name))
print(name[0:5])
print(name[1:11])
print(name[:11])
print(name[:])

nm = "harry"
print(len(nm))
print(nm[0:-3])
print(nm[-3:-1])
print(nm[-4:-2])

# STRING WITH SKIP VALUE :-

name = "harry,parry"
print(name[1:10:2])
