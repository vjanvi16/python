# Escape Sequence in python :-

#  1. \n = used for new line
#  2. \t = used for gives a tab
#  3. \" "\ = for gives " " in the sentence to be print as an output.
#  4. sep = used when there is multiple value in one sentance and u want to print them sepratly.
#  5. end = used when u want to end the sentance with special value.


print ("Hey I'm janvi \nI'm a Good Girl. ")
print("South\tKorea")
print("hey \"janvi\"")
print("harry",8,9,sep="~",end="thank u\n")
print("Hello")